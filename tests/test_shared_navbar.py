"""The top navigation must come from the shared nav.js/nav.css pair.

Every page used to hard-code its own link list and its own copy of the navbar
CSS, which is how the bar ended up different on almost every page (older pages
simply never learned about newer ones). These tests fail the moment a template
grows a private nav again.
"""

import re
import unittest
from pathlib import Path

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "ghc_api" / "templates"
STATIC_DIR = Path(__file__).resolve().parent.parent / "ghc_api" / "static"

# signup.html is deliberately nav-less: it is the one page an unapproved,
# unauthenticated visitor sees, so it must not advertise admin pages.
TEMPLATES_WITHOUT_NAV = {"signup.html"}


def _nav_templates():
    for path in sorted(TEMPLATE_DIR.glob("*.html")):
        if path.name not in TEMPLATES_WITHOUT_NAV:
            yield path


class SharedNavbarTests(unittest.TestCase):
    def test_every_page_uses_the_shared_placeholder(self) -> None:
        for path in _nav_templates():
            with self.subTest(template=path.name):
                text = path.read_text(encoding="utf-8")
                self.assertIn('id="app-nav"', text)
                self.assertIn("filename='nav.js'", text)
                self.assertIn("filename='nav.css'", text)
                self.assertRegex(text, r'id="app-nav"[^>]*data-title="')

    def test_no_template_ships_its_own_navbar_styles_or_links(self) -> None:
        for path in _nav_templates():
            with self.subTest(template=path.name):
                text = path.read_text(encoding="utf-8")
                self.assertNotRegex(
                    text,
                    r"\.navbar[ -][\w-]*\s*\{",
                    "navbar styling belongs in static/nav.css",
                )
                self.assertNotIn(
                    '<div class="navbar-actions">',
                    text,
                    "nav links are generated by static/nav.js",
                )

    def test_signup_page_has_no_navigation(self) -> None:
        text = (TEMPLATE_DIR / "signup.html").read_text(encoding="utf-8")
        self.assertNotIn("app-nav", text)

    def test_nav_links_point_at_registered_routes(self) -> None:
        """Guard against a nav entry that 404s after a route rename."""
        from ghc_api.app import create_app

        nav_js = (STATIC_DIR / "nav.js").read_text(encoding="utf-8")
        hrefs = set(re.findall(r"href:\s*'([^']+)'", nav_js))
        self.assertTrue(hrefs, "nav.js should declare link targets")

        client = create_app().test_client()
        for href in sorted(hrefs):
            path = href.split("#")[0].split("?")[0]
            with self.subTest(href=href):
                self.assertNotEqual(client.get(path).status_code, 404)


class NavScriptContractTests(unittest.TestCase):
    """Cheap structural checks on the script itself (no DOM available here)."""

    def setUp(self) -> None:
        self.nav_js = (STATIC_DIR / "nav.js").read_text(encoding="utf-8")

    def test_secondary_menu_holds_the_occasional_tools(self) -> None:
        secondary = self.nav_js.split("var SECONDARY", 1)[1].split("];", 1)[0]
        for label in (
            "Runtime Config Override",
            "Code Agent",
            "Request Stats",
            "API Stats",
        ):
            self.assertIn(label, secondary)

    def test_primary_bar_stays_short(self) -> None:
        primary = self.nav_js.split("var PRIMARY", 1)[1].split("];", 1)[0]
        self.assertLessEqual(primary.count("href:"), 6)

    def test_runtime_config_falls_back_to_the_dashboard_hash(self) -> None:
        self.assertIn("'/#runtime-config'", self.nav_js)
        dashboard = (TEMPLATE_DIR / "dashboard.html").read_text(encoding="utf-8")
        self.assertIn("window.location.hash === '#runtime-config'", dashboard)


if __name__ == "__main__":
    unittest.main()
